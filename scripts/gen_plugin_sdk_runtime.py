#!/usr/bin/env python3
"""Embed the plugin SDK runtimes in the compiler.

`lyric plugin sdk` writes a static protocol runtime next to the generated API
code for each language (D207, docs/69 §13).  The runtimes are real source files
under lyric-compiler/lyric/plugin_tools/sdk/ so they can be read, compiled and
tested directly; the compiler carries them as string constants in
lyric-compiler/lyric/plugin_tools/sdk_runtime.l, which this script regenerates.
`--check` exits non-zero when the committed .l file is stale
(scripts/ci/plugin-sdk-e2e.sh runs it, so the two cannot drift).
"""
import os
import sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SDK = os.path.join(ROOT, "lyric-compiler", "lyric", "plugin_tools", "sdk")
DST = os.path.join(ROOT, "lyric-compiler", "lyric", "plugin_tools", "sdk_runtime.l")


def raw(text):
    # Same delimiter rule as `lyric fmt` (fmt_core.l rawStringLit), so the
    # generated file is already in the formatter's canonical form.
    hashes = ""
    while '"' + hashes in text:
        hashes += "#"
    return "r" + hashes + '"' + text + '"' + hashes


def read(*parts):
    with open(os.path.join(SDK, *parts), encoding="utf-8") as f:
        return f.read()


def render():
    java_dir = os.path.join(SDK, "java", "lyric", "plugin")
    java_files = sorted(f for f in os.listdir(java_dir) if f.endswith(".java"))
    out = [
        "//! Generated by scripts/gen_plugin_sdk_runtime.py from plugin_tools/sdk/. Do not edit.",
        "//!",
        "//! The static runtimes `lyric plugin sdk` writes beside the generated code",
        "//! (D207, docs/69 §13).",
        "package Lyric.PluginSdk",
        "",
        "import Std.Core",
        "import Std.Collections",
        "",
        "pub func csharpRuntimeSource(): String {",
        "  " + raw(read("csharp", "LyricPluginRuntime.cs")),
        "}",
        "",
        "pub func typescriptRuntimeSource(): String {",
        "  " + raw(read("typescript", "runtime.ts")),
        "}",
        "",
        "/// The runtime's files under `lyric/plugin/`.",
        "pub func javaRuntimeFileNames(): List[String] {",
        "  val names: List[String] = newList()",
    ]
    for name in java_files:
        out.append('  names.add("' + name + '")')
    out += ["  names", "}", "", "pub func javaRuntimeFile(name: in String): String {"]
    for name in java_files:
        out.append('  if name == "' + name + '" {')
        out.append("    return " + raw(read("java", "lyric", "plugin", name)))
        out.append("  }")
    out += ['  ""', "}", ""]
    return "\n".join(out)


def main():
    text = render()
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        have = open(DST, encoding="utf-8").read() if os.path.exists(DST) else ""
        if have != text:
            print("plugin_tools/sdk_runtime.l is stale: run scripts/gen_plugin_sdk_runtime.py", file=sys.stderr)
            return 1
        return 0
    with open(DST, "w", encoding="utf-8") as f:
        f.write(text)
    return 0


sys.exit(main())
